vm.runInThisContext(fs.readFileSync('js/listening-ladder.js','utf8'));
const a=(x,m)=>{if(!x)throw new Error(m)},L=global.WordDragonListeningLadder;
let p={xp:77,stats:{word:{mastered:true}},stageGates:{0:{passed:true}}};
const before=JSON.stringify({xp:p.xp,stats:p.stats,stageGates:p.stageGates});
let q=L.create(p,{repair:true});
a(q.view().level==='blind'&&q.view().reveal==='none','must begin blind');
a(q.view().blindPerfectEligible===true,'blind perfect should start eligible');
let out=q.correct();
a(out.success&&out.blindPerfect&&out.repairCompleted,'first blind correct must be perfect and repair success');
q=L.create(p,{repair:true});q.wrong();
a(q.view().level==='hint'&&q.view().reveal==='partial','first miss must reveal partial hint');
a(!q.view().blindPerfectEligible,'hint cannot retain blind perfect');
out=q.correct();
a(out.success&&!out.blindPerfect&&out.level==='hint','hint recovery incorrectly counted perfect');
q=L.create(p,{repair:true});q.wrong();q.wrong();
a(q.view().level==='full'&&q.view().reveal==='full','second miss must reveal full sentence');
out=q.correct();a(out.level==='full'&&!out.blindPerfect,'full recovery incorrectly counted perfect');
q=L.create(p,{repair:true});out=q.cancel();a(!out.success&&out.repairCompleted===false,'cancel must not complete repair');
a(p.listeningLadder.blindPerfect===1,'blind perfect telemetry wrong');
a(p.listeningLadder.hintRecoveries===1&&p.listeningLadder.fullRecoveries===1,'recovery telemetry wrong');
